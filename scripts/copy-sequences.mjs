#!/usr/bin/env node
// Bundle the sequence library into the extension.
// Source of truth: sequences/*.json (validated by sequences/validate.mjs).
// Output: extension/sequences/<file>.json + extension/sequences/index.json (what the popup's
// "Load a template" dropdown reads). Run by `npm run sequences:bundle`, the release gate and CI.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'sequences');
const dst = path.join(root, 'extension', 'sequences');

fs.mkdirSync(dst, { recursive: true });
for (const f of fs.readdirSync(dst)) if (f.endsWith('.json')) fs.unlinkSync(path.join(dst, f));

const files = fs
  .readdirSync(src)
  .filter((f) => f.endsWith('.json') && f !== 'schema.json' && f !== 'index.json')
  .sort();

const sequences = [];
for (const file of files) {
  const doc = JSON.parse(fs.readFileSync(path.join(src, file), 'utf8'));
  if (!Array.isArray(doc.steps) || !doc.name) throw new Error(`${file}: not a sequence template`);
  fs.copyFileSync(path.join(src, file), path.join(dst, file));
  sequences.push({ file, name: doc.name, description: doc.description || '', audience: doc.audience || '' });
}

const index = {
  version: 1,
  note: 'Generated by scripts/copy-sequences.mjs from sequences/*.json. Do not edit by hand.',
  sequences,
};
fs.writeFileSync(path.join(dst, 'index.json'), JSON.stringify(index, null, 2) + '\n');
console.log(`bundled ${sequences.length} sequences into extension/sequences/`);
